# A few value labels are stored as Windows-1252 bytes inside these UTF-8
# Stata files. Repair those before matching the lookup, which is UTF-8.
repair_pasec_label_text <- function(x) {
  bad <- is.na(iconv(x, from = "UTF-8", to = "UTF-8"))
  if (any(bad, na.rm = TRUE)) x[bad] <- iconv(x[bad], from = "CP1252", to = "UTF-8")
  enc2utf8(x)
}

apply_english_labels_grd2 <- function(data, warn_unmatched = TRUE) {
  idx <- match(tolower(names(data)), tolower(pasec_grd2_labels_en$variable))
  missed_values <- character()
  data[] <- map2(data, seq_along(data), \(x, i) {
    lab <- pasec_grd2_labels_en$label_en[idx[i]]
    if (!is.na(lab)) attr(x, "label") <- lab
    vl <- attr(x, "labels", exact = TRUE)
    if (!is.null(vl) && length(vl)) {
      nm <- repair_pasec_label_text(names(vl))
      known <- !is.na(nm) & nm %in% names(pasec_grd2_value_labels_en)
      en <- unname(pasec_grd2_value_labels_en[nm])
      names(vl)[known] <- en[known]
      attr(x, "labels") <- vl
      if (any(!known)) {
        missed_values <<- c(
          missed_values,
          paste0(names(data)[i], " = ", nm[!known])
        )
      }
    }
    x
  })
  unmatched <- names(data)[is.na(idx)]
  if (warn_unmatched && length(unmatched) > 0) {
    message(
      length(unmatched), " column(s) have no English variable label and were left unchanged: ",
      paste(unmatched, collapse = ", ")
    )
  }
  if (warn_unmatched && length(missed_values) > 0) {
    message(
      length(missed_values), " value label(s) have no English translation and were left unchanged: ",
      paste(unique(missed_values), collapse = "; ")
    )
  }
  data
}
